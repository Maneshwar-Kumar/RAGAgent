"""Run scripted rider questions through the agent and print a reviewable transcript.

    python scripts/demo.py                         # built-in scenarios
    python scripts/demo.py "Why won't my bike start?" --attach samples/white_smoke.jpg
    python scripts/demo.py "Here is my manual. What should I check if it won't start?" --attach my_manual.pdf
    python scripts/demo.py --markdown docs/SAMPLE_TRANSCRIPTS.md   # also save transcript

Each scenario runs in a fresh session so answers cannot borrow context from each other.
"""

from __future__ import annotations

import argparse
import asyncio
import mimetypes
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from google.adk.runners import Runner  # noqa: E402
from google.adk.sessions import InMemorySessionService  # noqa: E402
from google.genai import types  # noqa: E402

from bike_manual_agent.agent import SELECTED, root_agent  # noqa: E402

RE, TVS = "royal-enfield-himalayan-450", "tvs-ronin"
# (question, attachment, pre-selected manual_id or None to let the agent ask)
SCENARIOS = [
    ("Why is this smoke coming from my bike?", "samples/white_smoke.jpg", RE),
    ("My bike won't start in the morning. What should I check?", None, RE),
    ("What tyre pressure should I run with a pillion?", None, RE),
    ("The engine misfires and then stops. What could be wrong?", None, RE),
    ("Which aftermarket exhaust gives the most power?", None, RE),
    ("The ABS lamp stays on after I start riding. What should I do?", None, TVS),
    ("Why is this smoke coming from my bike?", "samples/white_smoke.jpg", TVS),
    ("My bike won't start. What should I check?", None, None),
]


async def ask(runner: Runner, question: str, image: str | None, manual: str | None) -> dict:
    state = {SELECTED: manual} if manual else {}
    session = await runner.session_service.create_session(
        app_name=runner.app_name, user_id="demo", state=state
    )
    parts = [types.Part(text=question)]
    if image:
        path = Path(image) if Path(image).is_absolute() else ROOT / image
        mime = mimetypes.guess_type(path.name)[0] or "image/jpeg"
        blob = types.Blob(mime_type=mime, data=path.read_bytes(), display_name=path.name)
        parts.insert(0, types.Part(inline_data=blob))
    searches, answer = [], ""
    async for event in runner.run_async(
        user_id="demo", session_id=session.id, new_message=types.Content(role="user", parts=parts)
    ):
        for call in event.get_function_calls():
            if call.name == "search_manual":
                searches.append(call.args.get("query"))
        if event.is_final_response() and event.content and event.content.parts:
            answer = "".join(p.text or "" for p in event.content.parts if not p.thought)
    return {
        "question": question,
        "image": image,
        "manual": manual,
        "searches": searches,
        "answer": answer.strip(),
    }


def to_markdown(results: list[dict]) -> str:
    out = [
        "# Sample transcripts",
        "",
        "Generated by `python scripts/demo.py --markdown docs/SAMPLE_TRANSCRIPTS.md` against "
        "the Royal Enfield Himalayan 450 and TVS Ronin owner's manuals (Vertex AI, "
        "`gemini-3.8-flash`). Each question ran in a fresh session; the photo is AI-generated.",
        "",
    ]
    for i, r in enumerate(results, 1):
        out += [f"## {i}. {r['question']}", ""]
        if r["image"]:
            out += [f"![attached photo](../{r['image']})", "", f"_Attached photo: `{r['image']}`_", ""]
        out += [f"**Manual selected:** `{r['manual'] or 'none (agent must ask)'}`", ""]
        out += [f"**Manual searches:** {'; '.join(f'`{q}`' for q in r['searches']) or '(none)'}", ""]
        out += [r["answer"], "", "---", ""]
    return "\n".join(out)


async def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("question", nargs="?")
    parser.add_argument("--attach", help="Photo or PDF manual to attach to the question")
    parser.add_argument(
        "--manual",
        default=RE,
        help="manual_id to pre-select (use '' to let the agent ask which bike)",
    )
    parser.add_argument("--markdown", type=Path, help="Write the transcript to this file")
    args = parser.parse_args()

    scenarios = [(args.question, args.attach, args.manual or None)] if args.question else SCENARIOS
    runner = Runner(agent=root_agent, app_name="bike_manual_agent", session_service=InMemorySessionService())
    results = []
    for question, image, manual in scenarios:
        r = await ask(runner, question, image, manual)
        results.append(r)
        print(f"\n=== [{manual or 'no manual selected'}] Q: {question}" + (f"  [attached: {image}]" if image else ""))
        print(f"    searches: {r['searches']}")
        print(r["answer"])
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(to_markdown(results), encoding="utf-8")
        print(f"\nTranscript written to {args.markdown}")


if __name__ == "__main__":
    asyncio.run(main())
